    TEST_CASE("machine: LVM metadata parsing");
    {
        struct rs_jval lvm;
        struct rs_buf  err;
        const char    *bad[][2] = {
            { "vg {\n", "unterminated section" },
            { "}", "unexpected '}'" },
            { "a = \"x", "unterminated string" },
            { "a = 99999999999999999999999", "number too large" },
            { "a = -", "bad number" },
            { "a = ", "expected a value" },
            { "a = [1, 2", "unterminated list" },
            { "a = [x]", "expected a value" },
            { "= 1", "expected a name" },
            { "a 1", "expected '=' or '{'" },
            { "a = @", "expected a value" },
            { "a = 1 a = 2", "appears twice" },
            { "a{b{c{d{e{f{g{h{i{j{k{l{m{n{o{p{q{r{}}}}}}}}}}}}}}}}}}", "nested too deeply" },
        };
        size_t         i;

        rs_buf_init(&err);
        memset(&lvm, 0, sizeof(lvm));
        CHECK(rs_lvm_parse(lvm_metadata, strlen(lvm_metadata), &lvm, &err));
        v = rs_jobject_get(&lvm, "vg0");
        CHECK_INT(num(v, "extent_size"), 8192);
        CHECK_INT(rs_jobject_get(v, "status")->n, 3);
        CHECK_STR(rs_jobject_str(rs_jobject_get(rs_jobject_get(v, "physical_volumes"), "pv0"),
                                 "device"), "/dev/mapper/sda2_crypt");
        CHECK(rs_jobject_get(rs_jobject_get(v, "logical_volumes"), "root-lv.1+x") != NULL);
        CHECK_STR(rs_jobject_str(&lvm, "description"), "Created *after* executing 'lvcreate'");
        rs_jval_free(&lvm);
        CHECK(rs_lvm_parse("a = -5 b = \"q\\\"uote\"", 20, &lvm, &err));
        CHECK(rs_jobject_get(&lvm, "a")->neg);
        rs_jval_free(&lvm);
        CHECK(rs_lvm_parse("a = \"x\0y\"", 9, &lvm, &err) == false);
        rs_jval_free(&lvm);
        for (i = 0; i < sizeof(bad) / sizeof(bad[0]); i++)
        {
            rs_test_case = bad[i][1];
            rs_buf_reset(&err);
            CHECK(!rs_lvm_parse(bad[i][0], strlen(bad[i][0]), &lvm, &err));
            CHECK_CONTAINS(err.data, bad[i][1]);
            rs_jval_free(&lvm);
        }
        rs_buf_free(&err);
    }

