/* Writes `text` to dir/rel, creating the directories on the way. */
static void put(const char *dir, const char *rel, const char *text)
{
    char       *path = rs_xasprintf("%s/%s", dir, rel);
    const char *slash;
    size_t      i;
    int         fd;

    for (i = strlen(dir) + 1; path[i] != '\0'; i++)
    {
        if (path[i] == '/')
        {
            path[i] = '\0';
            (void)mkdir(path, 0755);
            path[i] = '/';
        }
    }
    slash = strrchr(path, '/');
    if (slash && slash[1] == '\0')
    {
        free(path);
        return;   /* a directory only */
    }
    fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    CHECK(fd >= 0);
    if (fd >= 0)
    {
        CHECK(write(fd, text, strlen(text)) == (ssize_t)strlen(text));
        (void)close(fd);
    }
    free(path);
}

static void put_bytes(const char *dir, const char *rel, const unsigned char *data, size_t len)
{
    char *path = rs_xasprintf("%s/%s", dir, rel);
    int   fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);

    CHECK(fd >= 0);
    if (fd >= 0)
    {
        CHECK(write(fd, data, len) == (ssize_t)len);
        (void)close(fd);
    }
    free(path);
}

static void be(unsigned char *p, uint64_t v, int bytes)
{
    int i;

    for (i = bytes - 1; i >= 0; i--)
    {
        p[i] = (unsigned char)(v & 0xff);
        v >>= 8;
    }
}

/* A LUKS2 header with its JSON area, 16 KiB in all. */
static unsigned char *luks2_header(size_t *len)
{
    static const char json[] =
        "{\"tokens\": {\"0\": {\"type\": \"systemd-tpm2\"}, \"1\": {\"keyslots\": []}}, "
        "\"keyslots\": {\"0\": {\"type\": \"luks2\", \"key_size\": 64, "
        "\"area\": {\"type\": \"raw\", \"encryption\": \"aes-xts-plain64\", \"key_size\": 64}, "
        "\"kdf\": {\"type\": \"argon2id\", \"time\": 4}}}, "
        "\"segments\": {\"0\": {\"type\": \"crypt\", \"offset\": \"16777216\", "
        "\"encryption\": \"aes-xts-plain64\", \"sector_size\": 4096}}}";
    unsigned char *h = rs_xcalloc(16384, 1);

    memcpy(h, "LUKS\xba\xbe", 6);
    be(h + 6, 2, 2);
    be(h + 8, 16384, 8);
    memcpy(h + 24, "rootfs", 6);
    memcpy(h + 168, "11111111-2222-3333-4444-555555555555", 36);
    memcpy(h + 4096, json, sizeof(json) - 1);
    *len = 16384;
    return h;
}

static unsigned char *luks1_header(void)
{
    unsigned char *h = rs_xcalloc(1024, 1);

    memcpy(h, "LUKS\xba\xbe", 6);
    be(h + 6, 1, 2);
    memcpy(h + 8, "aes", 3);
    memcpy(h + 40, "cbc-essiv:sha256", 16);
    memcpy(h + 72, "sha1", 4);
    be(h + 108, 32, 4);
    memcpy(h + 168, "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", 36);
    return h;
}

