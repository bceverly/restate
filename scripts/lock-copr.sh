# Regenerate .github/requirements/copr.txt: the newest copr-cli, and every
# package it pulls in, each pinned by version and hash for
# `pip install --require-hashes` in the release workflow's COPR job.
#
#   scripts/lock-copr.sh
#
# Run it when copr-cli needs to be newer, or when an advisory names a locked
# package. As with scripts/lock-semgrep.sh, the whole set is resolved together:
# the packages under copr-cli are its to choose.
#
# The resolve targets the CI runner (Python 3.12, x86-64 Linux), not this
# machine. It needs uv, or pipx to run uv without installing it.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

OUT=".github/requirements/copr.txt"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

if command -v uv > /dev/null 2>&1; then
  UV=(uv)
elif command -v pipx > /dev/null 2>&1; then
  UV=(pipx run uv)
else
  echo "lock-copr.sh: needs uv or pipx (sudo apt install pipx)" >&2
  exit 1
fi

# rich: copr-cli uses it and does not declare it.
printf '%s\n' copr-cli rich > "$WORK/copr.in"
"${UV[@]}" pip compile "$WORK/copr.in" --upgrade --generate-hashes --no-header --quiet \
  --python-version 3.12 --python-platform x86_64-unknown-linux-gnu -o "$WORK/lock.txt"

{
  cat <<'HEADER'
# Copyright (c) 2026 Bryan C. Everly
# SPDX-License-Identifier: BSD-2-Clause
#
# copr-cli for the release workflow's COPR job, every package pinned by
# version and hash so CI installs exactly these files (pip --require-hashes)
# and nothing a compromised index could substitute. Generated by
# scripts/lock-copr.sh for the runner's Python 3.12 on x86-64 Linux --
# regenerate it with that script rather than editing it, so the whole set
# stays one consistent resolve.
#
# Dependabot leaves this file alone; see .github/dependabot.yml.
HEADER
  # The input file's temporary path, in uv's "via" comments, means nothing here.
  sed "s|$WORK/copr.in|copr.in|g" "$WORK/lock.txt"
} > "$OUT"

echo "$OUT: $(grep -c '^[a-z0-9]' "$OUT") packages, $(grep -o '^copr-cli==[^ ]*' "$OUT")"
