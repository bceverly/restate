What makes this machine this machine:
.IR /etc ,
.IR /home ,
.IR /root ,
.IR /var/lib ,
.IR /usr/local .
Always recorded. A path that no rule covers is state: a file nobody meant to
keep costs some space, a file nobody meant to lose costs the restore.
.TP
