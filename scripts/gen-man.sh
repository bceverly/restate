.SH MACHINE
An index of the running system's own root \- a
.B capture
or
.B scan
of
.I /
\- also describes the machine underneath the files, in a
.B """machine"""
object, so that it can be rebuilt before the files are put back.
.B restate machine
prints the same description on its own.
.PP
It records the operating system (from
.IR os\-release ),
the kernel, the architecture, the host name and the media the machine was
first installed from; whether it is a desktop or a server, with the evidence
for that \- desktop metapackages, graphical sessions installed \- since the
installer chosen for a rebuild depends on it; whether it is bare metal or a
virtual machine, and on what, and whether it is a container; the hardware (from DMI: vendor, product, firmware
version), the processor, the memory and the physical network interfaces with
their addresses; UEFI or BIOS, the Secure Boot state, and the boot loaders
installed; every disk, with its size, sector sizes, model and serial number;
its partition table (GPT or MBR) and, for each partition, its offset, size,
type, UUID, name and flags, and what is on it \- a filesystem with its type,
UUID and label, LUKS, an LVM physical volume, a RAID member; the
device-mapper devices built on them; each LVM volume group's own metadata, as
.I /etc/lvm/backup
holds it; software RAID arrays; the persistent filesystems mounted, with their size and the space used on
each \- what a replacement disk, or a virtual one, actually has to hold \- and
.IR /etc/fstab ,
.I /etc/crypttab
and the swap in use.
.PP
All of it is read from files \- sysfs, the udev database,
.IR /proc ,
.I /etc
\- except a LUKS volume's cipher, key size and key-derivation function, which
are in the volume's header and need root to read, as are its LUKS2 tokens:
a
.B systemd\-tpm2
or
.B clevis
token means the volume unlocks with this machine's TPM or a network server,
and will not unlock that way on any other machine. No key, passphrase or key
slot is ever recorded. Anything that could not be read is listed in the
description's
.B """notes"""
rather than guessed.
.PP
On the BSDs the kernel is asked instead, each in its own terms: on FreeBSD,
GEOM's configuration
.RB ( "sysctl kern.geom.conftxt" :
disks, GPT and MBR partitions, GELI providers) and the boot method; on
OpenBSD, each disk's disklabel; on NetBSD, the wedges of a GPT disk or the
disklabel of any other \- the last two need root, as reading a disklabel
does. The hardware comes from
.BR sysctl (3),
the interfaces from
.BR getifaddrs (3)
and the mounts from
.BR getmntinfo (3).
On macOS, whose disks are described through Disk Arbitration rather than
libc, the description holds the system, hardware, interfaces and mounts, and
a note saying so.
.B buildsheet
and
.B autoinstall
are written for Linux in this version.
.PP
An index of any other tree \- a disk mounted from another machine, a
directory \- has no machine description, because the disks it would describe
are this machine's, not that tree's.
.SH PACKAGES
A reinstall puts back the distribution's own packages; everything installed
since \- by apt from the archive, a PPA or a vendor's repository, by snap or
flatpak, by pip, npm or cargo \- has to be installed again, and the rules
leave it out of an image, because a package manager puts it back. So every
.B capture
and
.B scan
records what is installed, and where it came from, in a
.B """packages"""
object.
.B restate packages
prints the same inventory on its own, of this tree or of the one an image
was taken from. All of it is read from the package managers' own files,
never by running them, so the inventory of a tree mounted from another disk
is that tree's.
.PP
For apt it records every package dpkg has unpacked, with its version and
architecture; whether it was installed by hand or as a dependency (from
.IR /var/lib/apt/extended_states );
whether it is held; and how far dpkg got with one it did not finish. It
records every repository in
.I /etc/apt/sources.list
and
.IR /etc/apt/sources.list.d ,
in either format, with the key each is signed with, and every key file apt
trusts \- whole, wherever it is, because a key under
.I /usr/share/keyrings
is not kept in an image, and apt refuses a repository whose key is missing.
Only public keys are there to record. From apt's package lists it records
which repositories each installed version can be had from again, and, for
the ones none can, why:
.B """superseded"""
where a repository has another version of the package now \- with
.B superseded_in
naming those repositories and
.B installed
when this version went in, which is when the archive's snapshot has it \- and
.B """local"""
where none has it at all \- it was installed from a
.I .deb
file, and only that file puts it back. The lists are as fresh as the last
.BR "apt update" .
.PP
Each source is checked, too, as apt checks it: its index as apt last fetched
it \-
.IR InRelease ,
or
.I Release
and
.I Release.gpg
\- against the keys it names with
.B Signed\-By
(or else apt's
.I trusted.gpg
and
.IR trusted.gpg.d ,
or the key written into the source's own
.I .sources
file, as Ubuntu writes a PPA's),
with
.BR gpgv (1),
and its
.B Valid\-Until
against the time now. apt refuses a source whose key has gone, changed or
expired once, in an
.B apt update
nobody reads, and goes on with the last index it accepted, for months; a
rebuild installs from the source as it is now, and gets nothing from it. A
source apt cannot use has a
.B """problem"""
saying why, and
.B capture
warns of each one.
.PP
That is what apt last fetched. With
.BR \-\-fetch\-sources ,
each source that passes is fetched again as its repository serves it now,
with
.BR curl (1)
\- plain http as well as https, since what is fetched is checked by its
signature rather than its transport \- and checked the same way, so a vendor
that has moved to a new key since the last
.BR "apt update" ,
or a repository that has gone, is caught before a rebuild finds out.
.PP
For snap it records each snap's revision, channel and confinement, from
snapd's state, which only root can read; otherwise the revisions alone, from
.IR /snap ,
and a note. A snap installed from a file rather than the store is marked
.BR """local""" .
For flatpak it records the remotes and the apps of each installation, the
system's and each user's. For pip, npm, cargo, pipx and Ruby gems it records
what was installed outside any project: system-wide, and in the home
directory of root and of each user who logs in. On OpenBSD and NetBSD it
records the installed packages. It records the alternatives chosen by hand
.RB ( "update-alternatives \-\-set" ),
and what each points at; the rest follow the packages by themselves.
Other package managers \- rpm, pacman, apk,
Nix, Guix, Homebrew, conda, FreeBSD's
.BR pkg ,
macOS receipts \- are listed in
.B """managers"""
as present, with no inventory in this version, so that an image says what it
is missing rather than leaving it out silently.
.PP
With
.BR \-\-keep\-local\-packages ,
a capture also keeps the files that put back what no repository or store
can: the
.I .deb
of each installed version no repository has, from apt's cache
.RI ( /var/cache/apt/archives ),
and the
.I .snap
of each snap installed from a file, from snapd's
.RI ( /var/lib/snapd/snaps ),
in the image's kit as well as its files. Both caches are left out of an image
otherwise. A package installed from a downloaded file is often not in apt's
cache; the capture warns of each one it cannot keep, and
.B dpkg\-repack
.I NAME
run in
.I /var/cache/apt/archives
rebuilds one from what is installed, under the name the next capture looks
for. Where that will not do \- dpkg\-repack refuses a package whose own
maintainer scripts have the wrong permissions \-
.BI \-\-deb " NAME" = FILE
names the
.I .deb
to keep for package
.IR NAME ,
wherever it is; it has to be a
.I .deb
file, and
.I NAME
a package no repository has. A superseded version, one a repository has a
newer version of, is kept if it is in the cache and passed over quietly if
not, since a rebuild installs the newer one \- or, with
.BR \-\-exact\-versions ,
this one, from the archive's snapshot as of when it was installed.
.B verify
walks the files an image kept, so they are not reported as deleted. Off by
default: those files can be large.
.SH BASELINE
.I Baseline
means
.I supplied by the operating system or its packages
\- the files a reinstall puts back on its own. The rules say where only
packages put files:
.IR /usr ,
.IR /bin ,
.IR /sbin ,
.IR /lib ,
.IR /boot ,
and the equivalents on each system, as
.B restate rules
lists them. On a system dpkg manages, the package manager then says which
files those are. dpkg records, for every package installed, each file it put
there and an MD5 digest of what it put there
.RI ( /var/lib/dpkg/info/*.md5sums ,
and for configuration files the
.B Conffiles
of
.IR /var/lib/dpkg/status ),
and every regular file the rules call baseline or state is checked against
it:
.IP \(bu 2
A file that still matches what its package installed is baseline, and the
index names the package, wherever the file is \- an unchanged configuration
file in
.IR /etc ,
a vendor's files in
.IR /opt .
Reinstalling the package puts it back, so its content is not kept.
.IP \(bu 2
A file that no longer matches is state, marked
.B modified
in the index, and kept: an edited configuration file, a patched binary.
.IP \(bu 2
A file in a baseline tree that no package installed is state, and kept: it
was put there by hand.
.PP
What packages' own scripts generate beneath those trees \- initramfs images,
module indexes, icon and font caches, the compiled MIME and schema databases,
the boot loader's files \- no package owns either, and the built-in rules
make each of them expendable rather than keep it. Diversions are followed,
and on a merged
.I /usr
a file dpkg lists under
.I /bin
is found under
.IR /usr/bin .
.B \-\-rules\-only
turns the check off and classifies by the rules alone, as on a system with no
dpkg, where a baseline file changed or added by hand is recorded but not
kept; keep those with
.BR \-\-baseline\-content ,
or name them as state in a rules file.
.PP
MD5 is what dpkg records, so it is what is compared. It is not used to
protect anything: a file made to match the digest of a packaged one would
need a second preimage, which MD5 still resists. Every digest restate
records itself is SHA-256.
.PP
The baseline is not read from an installation image, and does not depend on
whether a machine was installed as a desktop or a server, or for which
processor: it is decided on the machine in front of it, so whatever was
installed there is what it sees. (The installer still matters for putting a
machine back, and
.B restate installer
names and fetches it; see
.BR INSTALLERS .)
A baseline file is recorded in the index with
its owner, mode, times and SHA-256, and its content is left out of an image
unless
.B \-\-baseline\-content
is given.
.SS Fetching the packages
The packages themselves, at the versions recorded, are another matter: the
archive moves on, and a vendor that keeps only its newest release drops the
rest.
.B restate baseline
lists every apt package a machine has \- or the one an image was taken
from \- and whether the cache has it, and
.B restate baseline fetch
downloads each at its version, as a
.I .deb
named as apt names it in its own cache, into
.I /var/cache/restate/baseline
.RB ( \-\-cache
to change that), where
.B restore \-\-packages
installs from.
.PP
Each repository's index \-
.IR InRelease ,
or
.I Release
and
.I Release.gpg
\- is checked with
.BR gpgv (1)
against the keys its source names, as apt checks it, and only the text the
signature covers is read; each
.I Packages
list is checked against the index's SHA-256 for it, and each
.I .deb
against the list's, before it is renamed into the cache. A version the
archive no longer has is looked for in its snapshot \- as of the capture, or,
for one the archive had moved on from already, as of when it was installed
\- on snapshot.ubuntu.com and snapshot.debian.org, signed by the same keys.
Run again, it checks what the cache has and downloads only what is missing or
does not match. The packages are installed as root, so fetching an image's is
held to restore's rule: the image has to be signed by a
.BR \-\-trusted\-key ,
or the fetch given
.BR \-\-allow\-unverified .
A repository that wants a login, as Ubuntu Pro's does, is given the one apt
has, from
.I /etc/apt/auth.conf
and
.IR /etc/apt/auth.conf.d ,
so for those the fetch runs as root:
.BR curl (1)
is handed only the entries for hosts the sources reach over HTTPS and never
over plain HTTP, in a file of its own removed when the fetch ends.
Exit status 3 if any could not be had. What was installed from a
.I .deb
no repository has, only an image can keep
.RB ( "capture \-\-keep\-local\-packages" ).
.SH INSTALLERS
.B restate installer
names the installation image a machine is rebuilt from, worked out from its
machine description: the distribution and release, the point release, the
architecture, and whether it is a desktop or a server, with the evidence for
that. Given an image, index or saved description, it names the installer for
the machine that was captured rather than this one. Ubuntu is supported in
this version: the desktop image for a desktop on amd64 or arm64, and the
server image otherwise, from
.I releases.ubuntu.com
(and
.I old\-releases.ubuntu.com
once a release reaches end of life) for amd64, and
.I cdimage.ubuntu.com
for other architectures.
.PP
.B restate installer fetch
downloads it. The vendor's
.I SHA256SUMS
and its signature are fetched first and checked with
.BR gpgv (1)
