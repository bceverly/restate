.SH NAME
restate \- back up what a fresh OS install would not put back, to rebuild the machine
.SH SYNOPSIS
.B restate
.RI [ option ...]
.I command
.RI [ argument ...]
.SH DESCRIPTION
.B restate
records what makes this machine different from a fresh install of its
operating system, so that after the disk is wiped and the system reinstalled,
the difference can be put back.
.PP
A full backup copies every file. Most of those files came from the operating
system or its packages and can be fetched again; what cannot be fetched again
is the configuration, the data and the local changes. That difference is
usually a small fraction of the disk, and it is what
.B restate
records.
.PP
Every path is given a class by a list of rules (see
.BR CLASSES " and " RULES
below), and
.B capture
walks the tree writing an
.IR image :
a gzip'd tar holding an
.I index
of every recorded path and the content of everything worth keeping (see
.BR "IMAGES AND INDEXES" ).
.B scan
writes the index alone. Two images or indexes can be compared with
.BR diff ,
and either compared against the tree as it is now with
.BR verify .
.PP
The walk never follows a symbolic link, never opens a path longer than one
component, and checks every directory and file it opens against what it was
told it would find, so that a tree being changed underneath it cannot steer it
somewhere else.
.SH COMMANDS
Options may appear before or after the command.
HEADER

  section "Commands" | entries command

  printf '.SH OPTIONS\n'
  section "Options" | entries option

  cat <<'CLASSES'
.SH CLASSES
.TP
.B ephemeral
Runtime state with no meaning after a reboot:
.IR /proc ,
.IR /run ,
.IR /tmp ,
process ID files and sockets. Never recorded, and never descended into.
.TP
.B expendable
Could be kept, but a rebuilt machine does not need it, because it can be
fetched or rebuilt from something else: caches, downloads, dependencies,
installed toolchains, logs; see
.BR "WHAT IS LEFT OUT" .
Not recorded unless
.B \-\-all
is given, or a rule makes it state.
.TP
.B baseline
Supplied by the operating system or its packages:
.IR /usr ,
the kernel, and on a system dpkg manages, any file still as its package
installed it; see
.BR BASELINE .
Recorded with content digests, but not kept.
.TP
.B state
What makes this machine this machine:
.IR /etc ,
.IR /home ,
.IR /root ,
.IR /var/lib ,
.IR /usr/local .
Always recorded. A path that no rule covers is state: a file nobody meant to
keep costs some space, a file nobody meant to lose costs the restore.
.SH RULES
A rule is a class and a pattern, one per line:
.PP
.RS
.nf
state       /srv
expendable  /srv/cache    # comments start with a '#' after a space
ephemeral   *.sock
.fi
.RE
.PP
The
.B last
rule that covers a path decides its class, as in
.BR gitignore (5),
so a site rules file given with
.B \-\-rules
overrides any built-in rule. A rule covers the path it names and everything
beneath it. Because an ephemeral or expendable directory is not descended
into, no later rule can rescue something inside one; classify the directory as
state and its unwanted children as expendable instead.
.PP
In a pattern,
.B *
matches any run of characters except
.BR / ,
.B **
matches any run including
.BR / ,
.B **/
matches zero or more whole directories,
.B ?
matches one character except
.BR / ,
and a backslash makes the next character literal. A pattern that does not
begin with
.B /
matches at any depth.
.PP
The built-in rules are chosen by operating system: linux, freebsd, openbsd,
netbsd and darwin.
.B restate rules
prints them in this format, with the reason for each, so that a site that
disagrees can save them, edit them, and run with
.BR "\-N \-R" " file" .
.SH WHAT IS LEFT OUT
By default an image holds what cannot be had again any other way. Anything
that can be downloaded again, or rebuilt from files the image does keep, is
expendable, so it costs neither time nor space in a capture:
.TP
.B Downloads
.I ~/Downloads
in every user's home, wherever homes are kept
.RI ( /home ,
.I /usr/home
on FreeBSD,
.I /Users
on macOS, and root's).
.TP
.B Caches and the trash
.IR ~/.cache ,
the desktop's trash and the trash on other drives, thumbnails, the caches
Chrome, Chromium, Brave, Edge and Electron apps keep inside their profiles
(service-worker, compiled-code and GPU shader caches \- not bookmarks,
logins or site data),
.IR /var/cache ,
SonarScanner's cache, and on macOS the per-user and sandboxed apps' caches.
.TP
.B Dependencies
Anything a lock file or a manifest installs again:
.IR node_modules ,
npm, Yarn, pnpm and Bun caches, Python virtual environments
.RI ( .venv ,
.IR venv ,
.IR ~/.venvs ,
pipenv's), Gradle, Maven, Ivy, Cargo, Go, NuGet, Dart, Haskell and conda
caches, installed Ruby gems, Terraform providers.
.TP
.B Build output
Compiled Python, object files, CMake's build files, Next.js, Nuxt, Parcel,
Turborepo and Zig caches, ccache, and Xcode's DerivedData.
.TP
.B Installed toolchains and apps
What a version manager or store installs again: nvm, pyenv, rbenv, asdf,
mise, Volta, SDKMAN!, ghcup, elan and rustup toolchains; Julia packages; VS
Code extensions and its remote server; the Android SDK, PlatformIO, Arduino
and JetBrains Toolbox installs; Steam games; Flatpak apps and runtimes
(their remotes and overrides are kept); snaps; Ollama models.
.TP
.B Images
Container images and layers (containerd, Docker, Podman \- not their
volumes, which are data), LXD's image cache, installer images libvirt boots
from, the snaps the installer seeded, and installer and disc images
.RI ( *.iso ),
cloud images and downloads that never finished
.RI ( *.part ,
.IR *.crdownload ). Virtual machines' own disks and
definitions are data, and are kept; a suspended VM's saved memory is not,
and without it the VM boots afresh.
.TP
.B Never at all
Swap files, process IDs and sockets, per-filesystem
.IR lost+found ,
the last X session's error log; and
.IR /proc ,
.IR /sys ,
.IR /run ,
.IR /tmp ,
.IR /mnt ,
.I /media
and the like.
.PP
None of it is lost for good by being left out: it is kept with
.BR \-\-all ,
or one piece at a time with a rule in a rules file, since a site's rules
come after the built-in ones and the last match wins:
.PP
.RS
.nf
state  /home/alice/Downloads        # keep one user's downloads
state  /srv/app/node_modules        # an app deployed with its dependencies
state  **/.venv                     # every virtual environment
.fi
.RE
.PP
.B restate classify
says which rule decided a path, and
.B restate rules
lists every rule with its reason.
.SH MACHINE
An index of the running system's own root \- a
.B capture
or
.B scan
of
.I /
\- also describes the machine underneath the files, in a
.B """machine"""
object, so that it can be rebuilt before the files are put back.
.B restate machine
prints the same description on its own.
.PP
It records the operating system (from
.IR os\-release ),
the kernel, the architecture, the host name and the media the machine was
first installed from; whether it is a desktop or a server, with the evidence
for that \- desktop metapackages, graphical sessions installed \- since the
installer chosen for a rebuild depends on it; whether it is bare metal or a
virtual machine, and on what, and whether it is a container; the hardware (from DMI: vendor, product, firmware
version), the processor, the memory and the physical network interfaces with
their addresses; UEFI or BIOS, the Secure Boot state, and the boot loaders
installed; every disk, with its size, sector sizes, model and serial number;
its partition table (GPT or MBR) and, for each partition, its offset, size,
type, UUID, name and flags, and what is on it \- a filesystem with its type,
UUID and label, LUKS, an LVM physical volume, a RAID member; the
device-mapper devices built on them; each LVM volume group's own metadata, as
.I /etc/lvm/backup
holds it; software RAID arrays; the persistent filesystems mounted, with their size and the space used on
each \- what a replacement disk, or a virtual one, actually has to hold \- and
.IR /etc/fstab ,
.I /etc/crypttab
and the swap in use.
.PP
All of it is read from files \- sysfs, the udev database,
.IR /proc ,
.I /etc
\- except a LUKS volume's cipher, key size and key-derivation function, which
are in the volume's header and need root to read, as are its LUKS2 tokens:
a
.B systemd\-tpm2
or
.B clevis
token means the volume unlocks with this machine's TPM or a network server,
and will not unlock that way on any other machine. No key, passphrase or key
slot is ever recorded. Anything that could not be read is listed in the
description's
.B """notes"""
rather than guessed.
.PP
On the BSDs the kernel is asked instead, each in its own terms: on FreeBSD,
GEOM's configuration
.RB ( "sysctl kern.geom.conftxt" :
disks, GPT and MBR partitions, GELI providers) and the boot method; on
OpenBSD, each disk's disklabel; on NetBSD, the wedges of a GPT disk or the
disklabel of any other \- the last two need root, as reading a disklabel
does. The hardware comes from
.BR sysctl (3),
the interfaces from
.BR getifaddrs (3)
and the mounts from
.BR getmntinfo (3).
On macOS, whose disks are described through Disk Arbitration rather than
libc, the description holds the system, hardware, interfaces and mounts, and
a note saying so.
.B buildsheet
and
.B autoinstall
are written for Linux in this version.
.PP
An index of any other tree \- a disk mounted from another machine, a
directory \- has no machine description, because the disks it would describe
are this machine's, not that tree's.
.SH PACKAGES
A reinstall puts back the distribution's own packages; everything installed
since \- by apt from the archive, a PPA or a vendor's repository, by snap or
flatpak, by pip, npm or cargo \- has to be installed again, and the rules
leave it out of an image, because a package manager puts it back. So every
.B capture
and
.B scan
records what is installed, and where it came from, in a
.B """packages"""
object.
.B restate packages
prints the same inventory on its own, of this tree or of the one an image
was taken from. All of it is read from the package managers' own files,
never by running them, so the inventory of a tree mounted from another disk
is that tree's.
.PP
For apt it records every package dpkg has unpacked, with its version and
architecture; whether it was installed by hand or as a dependency (from
.IR /var/lib/apt/extended_states );
whether it is held; and how far dpkg got with one it did not finish. It
records every repository in
.I /etc/apt/sources.list
and
.IR /etc/apt/sources.list.d ,
in either format, with the key each is signed with, and every key file apt
trusts \- whole, wherever it is, because a key under
.I /usr/share/keyrings
is not kept in an image, and apt refuses a repository whose key is missing.
Only public keys are there to record. From apt's package lists it records
which repositories each installed version can be had from again, and, for
the ones none can, why:
.B """superseded"""
where a repository has another version of the package now, and
.B """local"""
where none has it at all \- it was installed from a
.I .deb
file, and only that file puts it back. The lists are as fresh as the last
.BR "apt update" .
.PP
For snap it records each snap's revision, channel and confinement, from
snapd's state, which only root can read; otherwise the revisions alone, from
.IR /snap ,
and a note. A snap installed from a file rather than the store is marked
.BR """local""" .
For flatpak it records the remotes and the apps of each installation, the
system's and each user's. For pip, npm, cargo, pipx and Ruby gems it records
what was installed outside any project: system-wide, and in the home
directory of root and of each user who logs in. On OpenBSD and NetBSD it
records the installed packages. It records the alternatives chosen by hand
.RB ( "update-alternatives \-\-set" ),
and what each points at; the rest follow the packages by themselves.
Other package managers \- rpm, pacman, apk,
Nix, Guix, Homebrew, conda, FreeBSD's
.BR pkg ,
macOS receipts \- are listed in
.B """managers"""
as present, with no inventory in this version, so that an image says what it
is missing rather than leaving it out silently.
.PP
With
.BR \-\-keep\-local\-packages ,
a capture also keeps the files that put back what no repository or store
can: the
.I .deb
of each installed version no repository has, from apt's cache
.RI ( /var/cache/apt/archives ),
and the
.I .snap
of each snap installed from a file, from snapd's
.RI ( /var/lib/snapd/snaps ),
in the image's kit as well as its files. Both caches are left out of an image
otherwise. A package installed from a downloaded file is often not in apt's
cache; the capture warns of each one it cannot keep, and
.B dpkg\-repack
.I NAME
run in
.I /var/cache/apt/archives
rebuilds one from what is installed, under the name the next capture looks
for. Where that will not do \- dpkg\-repack refuses a package whose own
maintainer scripts have the wrong permissions \-
.BI \-\-deb " NAME" = FILE
names the
.I .deb
to keep for package
.IR NAME ,
wherever it is; it has to be a
.I .deb
file, and
.I NAME
a package no repository has. A superseded version, one a repository has a
newer version of, is kept if it is in the cache and passed over quietly if
not, since a rebuild installs the newer one.
.B verify
walks the files an image kept, so they are not reported as deleted. Off by
default: those files can be large.
.SH BASELINE
.I Baseline
means
.I supplied by the operating system or its packages
\- the files a reinstall puts back on its own. The rules say where only
packages put files:
.IR /usr ,
.IR /bin ,
.IR /sbin ,
.IR /lib ,
.IR /boot ,
and the equivalents on each system, as
.B restate rules
lists them. On a system dpkg manages, the package manager then says which
files those are. dpkg records, for every package installed, each file it put
there and an MD5 digest of what it put there
.RI ( /var/lib/dpkg/info/*.md5sums ,
and for configuration files the
.B Conffiles
of
.IR /var/lib/dpkg/status ),
and every regular file the rules call baseline or state is checked against
it:
.IP \(bu 2
A file that still matches what its package installed is baseline, and the
index names the package, wherever the file is \- an unchanged configuration
file in
.IR /etc ,
a vendor's files in
.IR /opt .
Reinstalling the package puts it back, so its content is not kept.
.IP \(bu 2
A file that no longer matches is state, marked
.B modified
in the index, and kept: an edited configuration file, a patched binary.
.IP \(bu 2
A file in a baseline tree that no package installed is state, and kept: it
was put there by hand.
.PP
What packages' own scripts generate beneath those trees \- initramfs images,
module indexes, icon and font caches, the compiled MIME and schema databases,
the boot loader's files \- no package owns either, and the built-in rules
make each of them expendable rather than keep it. Diversions are followed,
and on a merged
.I /usr
a file dpkg lists under
.I /bin
is found under
.IR /usr/bin .
.B \-\-rules\-only
turns the check off and classifies by the rules alone, as on a system with no
dpkg, where a baseline file changed or added by hand is recorded but not
kept; keep those with
.BR \-\-baseline\-content ,
or name them as state in a rules file.
.PP
MD5 is what dpkg records, so it is what is compared. It is not used to
protect anything: a file made to match the digest of a packaged one would
need a second preimage, which MD5 still resists. Every digest restate
records itself is SHA-256.
.PP
The baseline is not read from an installation image, and does not depend on
whether a machine was installed as a desktop or a server, or for which
processor: it is decided on the machine in front of it, so whatever was
installed there is what it sees. (The installer still matters for putting a
machine back, and
.B restate installer
names and fetches it; see
.BR INSTALLERS .)
A baseline file is recorded in the index with
its owner, mode, times and SHA-256, and its content is left out of an image
unless
.B \-\-baseline\-content
is given.
.SH INSTALLERS
.B restate installer
names the installation image a machine is rebuilt from, worked out from its
machine description: the distribution and release, the point release, the
architecture, and whether it is a desktop or a server, with the evidence for
that. Given an image, index or saved description, it names the installer for
the machine that was captured rather than this one. Ubuntu is supported in
this version: the desktop image for a desktop on amd64 or arm64, and the
server image otherwise, from
.I releases.ubuntu.com
(and
.I old\-releases.ubuntu.com
once a release reaches end of life) for amd64, and
.I cdimage.ubuntu.com
for other architectures.
.PP
.B restate installer fetch
downloads it. The vendor's
.I SHA256SUMS
and its signature are fetched first and checked with
.BR gpgv (1)
against the vendor's signing key, which is built into
.B restate
and pinned by fingerprint: a signature counts only when gpgv names that
fingerprint, not merely when it succeeds. The image listed for the machine's
own point release is chosen, or else the newest listed. It is downloaded with
.BR curl (1)
over HTTPS only, resuming an interrupted download, and checked against the
signed checksum; only then is it moved into place, and its path printed. An
image already in the cache that matches is not downloaded again.
.B \-\-cache
changes where images are kept, and
.B \-\-mirror
fetches from another https:// or file:// directory holding the same files \-
which are checked against the same key.
.SH PROGRESS
A capture of a whole machine can read hundreds of gigabytes and take an
hour, and by default says nothing until it is done.
.B \-\-progress
shows how far it has got:
.PP
.RS
.nf
restate: counting  812345 paths  184 GiB to read  0:00:41
restate: walking [#######.............]  35%  64 GiB of 184 GiB  91 MiB/s  0:22:30 left
  .../home/alice/dev/project/src/main.c
restate: writing [##############......]  70%  129 GiB of 184 GiB  305 MiB/s  0:03:01 left
.fi
.RE
.PP
A walk that reads files
.RB ( scan ,
.BR capture ,
.BR verify )
first counts them \- metadata only, no file is read, so this is quick \- to
know how many bytes the walk will read. The walk then shows a bar, a
percentage, how much has been read of how much, the throughput, the time
left at that rate, and under the bar the path being read. Writing an image,
the last step of a capture, shows the same against the content to be
written. Downloading an installer shows curl's own progress bar.
.PP
On a terminal the two lines are redrawn in place a few times a second, the
bar as wide as the terminal allows. They are drawn on the terminal even
when standard error is redirected \- to a log, through
.BR tee (1)
\- and each phase's final line is also written to standard error, so the
log records how each went. With no terminal at all, as under
.BR cron (8),
a line is written to standard error every ten seconds instead. It is off
unless asked for, and
.B \-\-quiet
does not turn it off: one option asks for silence about everything else,
the other for this.
.SH REBUILDING
.B restate buildsheet
writes a plain-text runbook for rebuilding the machine onto a blank disk:
the hardware and firmware it needs, the installer, the disk layout as it
was, and the commands that recreate it \-
.BR sfdisk (8)
for the partition tables,
.BR cryptsetup (8)
for LUKS,
.BR mdadm (8)
for RAID,
.BR pvcreate (8)
and
.BR vgcfgrestore (8)
for LVM (the volume group's own metadata backup, so every volume comes back
at its old extents), and
.BR mkfs (8)
and
.BR mkswap (8)
for the filesystems \- with the original UUIDs, so the restored
.I /etc/fstab
and
.I /etc/crypttab
still name the right volumes. Then how to point the installer at that
layout, what to do after it, how to install the packages again, and how to
put the files back. Nothing is run:
every command is printed for a person to check against
.BR lsblk (8)
and run.
.PP
The packages come from the image's inventory (see
.BR PACKAGES ),
and go back before the files, because a restored configuration file where a
package puts its own, or one naming a program not yet installed, makes
packages fail to install: first
.I /etc/apt
from the image and the repository keys kept outside it, written back from
the inventory with
.BR base64 (1);
then every package installed by hand, pinned to the version that was
installed, so it comes from the repository it came from and not another
that has the same name \- except the boot loader and the kernel, which the
installer chose for the machine it installed onto. They are installed by a
script that looks each one up first, because one that cannot be had \- a
vendor that keeps only its newest version, a repository whose key has
expired \- would otherwise stop a single
.B apt\-get install
of them all and install none: the version recorded where a repository still
has it, the current one where not, and a word about any none has; those
found together, or one at a time if apt refuses them together. Then the held
ones held again;
the ones the image keeps, installed from it; the ones no repository has any
more, or ever had, listed with what to do about them; then the snaps by
channel, the flatpak apps by remote, what pip, npm, pipx, cargo and gem
installed, each by its owner, and the alternatives chosen by hand. Every name and version in those commands is
quoted where it needs to be, because the inventory says whatever the
captured tree said. The restore that follows puts the old configuration
back over the packages' own.
.PP
Partitions that belong to another operating system \- Windows, BitLocker,
macOS, a VeraCrypt container \- are never formatted. Rebuilding the same
machine, the sheet offers two paths: a blank disk, where they are recreated
empty for that system's own restore, or the same disk, where the partition
table and the EFI system partition they boot from are left alone.
.PP
.B restate autoinstall
writes the same layout as an Ubuntu autoinstall file, for an install nobody
has to attend: storage in curtin's terms, locale, keyboard, time zone, host
name, network and the SSH server. A LUKS passphrase has to be in the file
for the installer to format the volume, and is left as CHANGE-ME, as is the
first account's password, which the restore replaces. The snaps are
installed at the new system's first boot, by a service the file leaves
behind
.RB ( restate\-firstboot ,
which removes itself; what it says is in its journal): the desktop
installer ignores an autoinstall file's
.B snaps
section, and snapd does not run while the system is being installed. Given
.B \-\-image\-at
.IR PATH ,
where the installer will find the image (a disk or share mounted there), its
late-commands do the rest of what the build sheet does, unattended and in
the same order: the packages, then the image's files over them \- keeping
the installer's
.I /etc/fstab
and
.IR /etc/crypttab ,
since it formatted the volumes \- and the initramfs and boot loader rebuilt.
A package that will not install is said in the installer's log and the
restore goes on; an image that is not there stops the install, saying so.
What only a person can do \- per-user installations, a package from a file
the image does not keep \- is listed in the file, for after the first boot.
.PP
With
.BR "\-\-target vm" ,
either one rebuilds the machine as a virtual machine: the Linux volumes only, each
filesystem sized to what it uses plus room to grow, disks named
.IR /dev/vda ,
and a
.BR virt-install (1)
command that gives the VM a modest share of a host \- at most 8 GiB of
memory and 4 CPUs, and never more than the original had, since a test
rebuild often runs on the very machine it came from; the hardware-only
packages (microcode, firmware and sensor tools, GPU drivers) are removed
and
.B qemu-guest-agent
added.
With
.BR "\-\-target metal" ,
it rebuilds on other hardware: the original sizes, the disk named by whoever
runs it, and the guest-only packages removed. Either way the sheet covers
what does not move: network interface names and MAC addresses, LUKS keys
held by the old machine's TPM, Secure Boot keys and the hibernation
resume device.
.SH RESTORING
.B restate restore
.I IMAGE
puts an image's files back under the root
.RB ( \-\-root ,
default
.IR / ).
The image is distrusted. Every member has to be an entry the index lists,
as the index lists it, and a member it does not list is refused. A regular
file is written beside its destination, hashed as it is written, and renamed
into place only if its digest is the index's, so a file that does not match
never lands. Every path is reached from the root one directory at a time,
never through a symbolic link: a link where a directory belongs is replaced,
not followed.
.PP
Owners, modes and times (to the nanosecond) come from the index, a
directory's only once everything in it is in; hard links are made links
again, and device nodes, which the index records but the image does not
archive, are made from the index.
.PP
Extended attributes come back as well \- on Linux, a file's POSIX ACLs
.RI ( system.posix_acl_access ,
and a directory's
.IR system.posix_acl_default )
and its capabilities
.RI ( security.capability )
among them. They are set after the owner, since a change of owner clears a
file's capabilities, and before the mode, since setting an ACL sets the
group bits from it; the users and groups an ACL names are mapped by name, as
owners are. SELinux and Smack labels and IMA and EVM signatures describe the
machine rather than the file, and are neither recorded nor set. FreeBSD and
NetBSD keep attributes in a user and a system namespace, recorded as
.I user.
and
.IR system. ;
OpenBSD has none.
.PP
Owners are restored by name. The system being restored onto has accounts
of its own: its packages made their system users as they were installed,
numbered in that order \- postgres may be 128 where it was 125 \- and its
installer made an account. So the image's
.IR /etc/passwd ,
.IR /etc/group ,
.I /etc/shadow
and
.IR /etc/gshadow ,
from its kit, are merged with the system's rather than laid over them. A
user or group both have keeps the system's number, which its packages'
files already carry, and a person (root, and uids from 1000) the image's
name, home and shell; every password is the image's; a group's members are
both systems'; a user or group only the image had keeps its number if it is
free, or takes the next free one in its range. Every file's owner is then
mapped through the merged accounts by the names the index records, and the
merged files are written in place of the image's.
.B \-\-numeric\-owner
restores the numbers the index records, and the image's account files as
they are, instead \- as an image from before 1.1, which has no kit, is
always restored. An autoinstall file creates the image's first person as
the install's own account, so no installer account is left on their number.
.PP
.B \-\-exclude
.I PATTERN
leaves paths out (a pattern as a rules file writes one, everything beneath
it too), and
.B \-\-dry\-run
reads and checks the whole image and says what would be put back, writing
nothing. The exit status is 3 if any file was refused, could not be written
or is missing from the image.
.PP
An image's kit carries the
.B restate
that made it, so a rebuilt system \- or an installer, with
.B \-\-root /target
\- can restore before restate is installed; the build sheet and the
autoinstall file do it that way, and fall back to tar where the kit has no
restate.
.SH IMAGES AND INDEXES
An image is an ordinary POSIX tar archive of three parts, each compressed on
its own:
.PP
.RS
.nf
restate/index.json.gz
restate/kit.tar.gz
restate/files.tar.gz
.fi
.RE
.PP
The index is first, and is all that
.BR verify ,
.BR diff ,
.BR packages ,
.B buildsheet
and
.B autoinstall
read. The kit holds what a reinstall needs before anything else \-
.IR /etc/apt ,
and the packages the image keeps that no repository has \- so that it can
be had in seconds. The files part holds every kept file, directory, symbolic
link and FIFO under
.IR restate/files ,
with its owner, mode and times (the kit's members too). The outer archive is
not compressed, so tar skips the parts it is not asked for rather than
reading them, and each part unpacks by hand when nothing else is available:
.PP
.RS
.nf
tar \-xOf IMAGE restate/files.tar.gz |
    tar \-xzpf \- \-\-numeric\-owner \-C / \-\-strip\-components=2
.fi
.RE
.PP
State is always kept; baseline content only with
.BR \-\-baseline\-content ,
because the operating system can supply it again. An image made before 1.1
is one gzip'd tar with
.I restate/index.json
first and the files after it, and is still read.
.PP
The index is JSON, one entry per line, sorted by path. Each entry records
the full
.I path
and its last component
.IR name ;
the
.I type
(file, directory, symlink, char, block, fifo) and
.IR class ;
the permission
.I mode
as an octal string; the numeric
.IR uid " and " gid
and the
.IR user " and " group
names behind them; the
.IR size ,
link count
.IR nlink ,
.IR device " and " inode ;
a device's
.IR rdev ;
the access, modification, status-change and birth times
.IR atime ,
.IR mtime ,
.IR ctime " and " btime ,
to the nanosecond in ISO 8601 UTC, with
.I btime
null where the filesystem keeps no birth time; a regular file's
.I sha256
digest, with
.B """unreadable"": true"
where it could not be read; a symbolic link's
.IR target ;
and, in an image, where the content is
.IR stored .
.PP
A JSON string must be UTF-8 and a file name need not be. A path or target
that is not valid UTF-8 is written lossily under its own key, for reading,
and exactly under the same key with
.B _base64
appended, which is what is read back.
.PP
The digest is SHA-256 rather than MD5: an MD5 collision can be made to
order, so two different files could compare equal. Every path read from an
index must be absolute and clean, with no
.BR . ,
.B ..
or empty component, or the index is rejected.
.PP
An image or index written with
.B \-\-output
is created with mode 0600, because it is a map of everything on the machine
and who owns it, and it replaces the previous file only once it is complete.
Reading a file to hash or keep it does not change its access time on Linux,
where
.B O_NOATIME
is available to the file's owner and to root; reading a symbolic link's
target does, and nothing can prevent that.
.PP
A file written to while it is copied \- a log, usually \- is kept as it
was when its copy began, with a digest of what was kept, and a warning says
so; it is not counted as unreadable. One that is cut short while copied, or
whose reading fails, is recorded as unreadable, and the exit status is 3.
.PP
An image can hold keys \- a LUKS key file under
.IR /etc ,
SSH host keys, TLS private keys \- so
.B \-\-encrypt\-to
encrypts it to the OpenPGP public key in a file
.RB ( "gpg \-\-export \-o key.gpg" ),
once for each recipient. Only a public key is needed to capture, so a
capture can run unattended with no passphrase anywhere, and only the holder
of a matching secret key can read the image.
.BR gpg (1)
runs in the same pipe as gzip, in an empty GnuPG home of its own that is
removed afterwards, once for each part of the image: each is an ordinary
OpenPGP message, its name ending in
.IR .gpg ,
that
.B gpg \-d
reads anywhere, and reading the index decrypts only the index. One thing is
not encrypted: while the tree is walked, the
content being kept is staged in an unlinked temporary file in the image's
directory, because the index comes first in the image and is not complete
until the walk is. It is never visible by name and is gone when
restate exits, but its blocks were written; where even that must not
happen, write the image to encrypted storage or a tmpfs.
.BR diff ,
.BR verify ,
.BR installer ,
.B buildsheet
and
.B autoinstall
read an encrypted image directly, decrypting with the invoking user's own
GnuPG keyring.
.PP
An image is compressed by
.BR pigz (1)
where it is installed \- the same gzip format, on every core, several times
faster on a large image \- and by gzip, with a warning saying so, where it
is not. Each is run as a separate process from a fixed path, never through
.BR PATH ;
see
.BR "SECURITY CONSIDERATIONS" .
