.SH LIVE SERVICES
A file copied while something writes to it can come back half old and half
new: a database's pages from two moments, a virtual machine's disk in the
middle of a write. So
.B capture
looks, in
.I /proc
(on Linux), for what is running and writing to files the image keeps \-
PostgreSQL, MySQL and MariaDB, MongoDB and Redis, by their data
directories; QEMU virtual machines, by the disks and NVRAM they hold open
for writing; LXD containers; and Docker, while a container runs, by its
volumes \- and names each one, with the command that would stop or pause
it.
.PP
With
.BR \-\-quiesce ,
it pauses each one instead, just in time: everything else is copied first,
then, for each in turn, it is paused, its own files are copied, and it is
resumed, so it is stopped for as long as its own files take, not the whole
capture. While one is paused, the signals that would end restate wait until
it is resumed again \- a Ctrl-C reaches the pausing itself, and stops what
is left \- and every pause and resume is said and logged to syslog, for a
capture run from cron.
.PP
restate pauses nothing itself; a hook does. A hook is an executable named
for the kind of thing it pauses \-
.BR postgresql ,
.BR mysql ,
.BR mongodb ,
.BR redis ,
.BR libvirt ,
.BR lxd ,
.B docker
\- looked for first in
.IR /etc/restate/hooks.d ,
then among the ones restate ships, in
.I libexec/restate/hooks
beside the directory restate is installed in. Either is run only if it and
its directory are root's and writable by no one else. It is run as
.I HOOK
.B pause
.I NAME
before the files are copied, and
.I HOOK
.B resume
.I NAME
after them \- always, even if pausing failed \- with
.BR RESTATE_ACTION ,
.BR RESTATE_KIND ,
.BR RESTATE_NAME ,
.BR RESTATE_PID ,
.BR RESTATE_UID " and " RESTATE_USER
(whose it is: a VM may be a user's own),
.B RESTATE_PATHS
(the paths about to be copied, one to a line) and
.B RESTATE_DUMP_DIR
in its environment. The dump directory,
.IR /var/lib/restate/dumps/ KIND\-NAME ,
root's and 0700, is copied into the image with the files once
.B pause
returns: the shipped database hooks put a dump there
.RB ( pg_dumpall ,
.BR mysqldump ,
.BR mongodump ),
which, unlike the data directory, can be loaded into another major version.
A hook that fails to pause is warned of, and the files are copied as they
are; resume is run all the same, and the capture ends incomplete, with exit
status 3, as one that fails to resume does. A pause may take 30 minutes and
a resume 10; then the hook is stopped.
.PP
The shipped hooks stop a database's service and start it again, suspend a
VM and resume it (through the user's own libvirt for a user's VM), freeze an
LXD container and thaw it, and pause Docker's running containers; one
paused already before is left so. The PostgreSQL hook also stops, first,
the units listed in
.I /etc/restate/also.d/postgresql
\- services that write to the database \- and starts them again after. To
change what a hook does, copy it to
.I /etc/restate/hooks.d
and change the copy.
.PP
What
.I /proc
does not show as one of these \- a service with a database of its own, an
application that wants to be told \- is named instead:
.BI \-\-quiesce\-with " NAME"
runs the hook
.I NAME
whether or not anything is found. It is asked first, as
.I HOOK
.B paths
.IR NAME ,
which paths it covers, one absolute path a line; those are left to the end
and copied while it is paused, as above. A hook that names none, or does not
know the question, is paused before the walk begins and resumed after it
ends. Two are shipped for this:
.B unifi
dumps the database the UniFi Network application runs itself (port 27117)
and stops its service, for
.I /var/lib/unifi
\- UniFi's own backups, in
.IR /var/lib/unifi/backup/autobackup ,
are in the capture too, and restore onto a new UniFi without restate \- and
.B nextcloud
puts Nextcloud in maintenance mode, for its own directory and its data
directory, while its database is paused by its own hook with
.BR \-\-quiesce .
A mail store kept as Maildir needs neither: every message is a file of its
own, written beside its name and renamed into place, so a copy taken while
mail arrives misses at most what arrived meanwhile.
.SH RESTORING
.B restate restore
.I IMAGE
puts an image's files back under the root
.RB ( \-\-root ,
default
.IR / ).
The image is distrusted. Every member has to be an entry the index lists,
as the index lists it, and a member it does not list is refused. A regular
file is written beside its destination, hashed as it is written, and renamed
into place only if its digest is the index's, so a file that does not match
never lands. Every path is reached from the root one directory at a time,
never through a symbolic link: a link where a directory belongs is replaced,
not followed. A file already in place as the image has it \- of the same
size and modification time, with no other name, whose content hashes to the
index's digest \- is not written again, only given its owner, mode,
attributes and times, so a restore run again needs no room beside a large
file for a second copy of it.
.PP
By itself that leaves a damaged image restored as far as it is whole. With
.BR \-\-check\-first ,
restore reads the whole image once before writing anything, checking every
file against the index, and refuses it \- exit status 2, nothing written \-
if any file is not what the index says or is missing; then it reads it again
to put it back.
.PP
Owners, modes and times (to the nanosecond) come from the index, a
directory's only once everything in it is in; hard links are made links
again, and device nodes, which the index records but the image does not
archive, are made from the index.
.PP
Extended attributes come back as well \- on Linux, a file's POSIX ACLs
.RI ( system.posix_acl_access ,
and a directory's
.IR system.posix_acl_default )
and its capabilities
.RI ( security.capability )
among them. They are set after the owner, since a change of owner clears a
file's capabilities, and before the mode, since setting an ACL sets the
group bits from it; the users and groups an ACL names are mapped by name, as
owners are. SELinux and Smack labels and IMA and EVM signatures describe the
machine rather than the file, and are neither recorded nor set. FreeBSD and
NetBSD keep attributes in a user and a system namespace, recorded as
.I user.
and
.IR system. ;
OpenBSD has none.
.PP
Owners are restored by name. The system being restored onto has accounts
of its own: its packages made their system users as they were installed,
numbered in that order \- postgres may be 128 where it was 125 \- and its
installer made an account. So the image's
.IR /etc/passwd ,
.IR /etc/group ,
.I /etc/shadow
and
.IR /etc/gshadow ,
from its kit, are merged with the system's rather than laid over them. A
user or group both have keeps the system's number, which its packages'
files already carry, and a person (root, and uids from 1000) the image's
name, home and shell; every password is the image's; a group's members are
both systems'; a user or group only the image had keeps its number if it is
free, or takes the next free one in its range. Every file's owner is then
mapped through the merged accounts by the names the index records, and the
merged files are written in place of the image's.
.B \-\-numeric\-owner
restores the numbers the index records, and the image's account files as
they are, instead \- as an image from before 1.1, which has no kit, is
always restored. An autoinstall file creates the image's first person as
the install's own account, so no installer account is left on their number.
.PP
.B \-\-exclude
.I PATTERN
leaves paths out (a pattern as a rules file writes one, everything beneath
it too), and
.B \-\-dry\-run
reads and checks the whole image and says what would be put back, writing
nothing. The exit status is 3 if any file was refused, could not be written
or is missing from the image.
.PP
.B \-\-packages
puts the old machine's packages back first, onto the running system, as root,
on a fresh install: the image's
.I /etc/apt
\- its repositories and the keys kept there \- and the keys kept elsewhere,
from its inventory; every package installed by hand, at its version where a
repository still has it, from the archive's snapshot with
.BR \-\-exact\-versions ,
and from the baseline (see
.BR BASELINE )
where none has it \- the baseline's cache is used only if it is root's and no
one else can write it; the
.I .deb
files the image kept; the holds; and each package marked installed by hand or
as a dependency, as it was. What the old machine did not have is marked a
dependency, so that
.B apt\-get autoremove
takes away what nothing it had needs \- never the kernel, the boot loader,
firmware, microcode or a virtual machine's guest tools (qemu\-guest\-agent,
open\-vm\-tools and the like), which follow the hardware, and nothing at all on a
machine of another architecture. Then the snaps, the system's flatpaks, the
Python, npm and Ruby packages installed system-wide, and the alternatives
chosen by hand; then the files, as without it, but for apt's own record of
what was installed by hand, which the packages have just set. It is done by a
.BR sh (1)
script, written and run by
.BR restate ;
with
.B \-\-dry\-run
it is written to standard output, or
.BR \-\-output ,
to read instead. Exit status 3 if the script did not finish cleanly.
.PP
An image says whose it is only if it is signed (see
.BR "IMAGES AND INDEXES" ),
so
.B restore
checks that before reading anything else. It refuses an image that is not
signed, carries a bad signature, or is signed by a key not given with
.BI \-\-trusted\-key " KEYFILE"
(a public key,
.BR "gpg \-\-export" ,
armored or not; repeatable), and exits 4, saying why. When it accepts one, it
says who signed it, and when and on which host the image was captured, so
an older image signed by the same key, substituted for the newest, is plain
to see.
.B \-\-allow\-unverified
restores it anyway, warning of what it found; it is an option on the command
line and nothing else \- no variable or file can set it.
.B verify
and
.B diff
check the same way when given
.BR \-\-trusted\-key ,
and refuse an image that fails.
.PP
An image's kit carries the
.B restate
that made it, so a rebuilt system \- or an installer, with
.B \-\-root /target
\- can restore before restate is installed; the build sheet and the
autoinstall file do it that way, and fall back to tar where the kit has no
restate. They pass
.B \-\-allow\-unverified
to it, unless they are made with
.BR \-\-trusted\-key :
then the build sheet's restore names the same key files, and the autoinstall
file carries the keys itself, for the installer's restore to check the image
