# Generate man/restate.8 from the program's own --help output.
#
#   scripts/gen-man.sh BINARY OUTPUT        write the manpage
#   scripts/gen-man.sh --check BINARY PAGE  fail if the committed page is stale
#
# The commands, options, exit statuses and examples in the manpage are not
# maintained by hand: they are read out of `restate --help`, which is itself
# generated from src/commands.def and src/options.def. Adding an option updates
# the parser, the help, the manpage and the README together, and `make lint`
# runs the --check mode so a page that was not regenerated fails rather than
# documenting an option that no longer exists.
#
# Only the prose sections below are written here: the part a generator cannot
# invent, and short enough to keep correct by reading it.
#
# The date in the .TH line is the one thing --check ignores -- the date, not
# the line, which also names the version -- and a page whose content has not
# changed keeps the date it already has. A date taken from a
# file's mtime changes on every fresh checkout, and a freshness check that
# fails on a clean clone is a check people learn to ignore.
set -euo pipefail

CHECK=0
if [ "${1:-}" = "--check" ]; then
  CHECK=1
  shift
fi

BINARY="${1:?usage: gen-man.sh [--check] BINARY OUTPUT}"
OUTPUT="${2:?usage: gen-man.sh [--check] BINARY OUTPUT}"

[ -x "$BINARY" ] || { echo "gen-man.sh: $BINARY is not executable" >&2; exit 1; }

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# The VERSION file, not --version: a working build reports "-dev", and the
# manpage is a committed file that names the release.
VERSION="$(cat "$REPO_ROOT/VERSION")"

# Today, unless the existing page carries a date already; see above.
DATE="$(date -u '+%B %d, %Y')"
DATE="${DATE/ 0/ }"
if [ -f "$OUTPUT" ]; then
  OLD_DATE="$(sed -n 's/^\.TH RESTATE 8 "\([^"]*\)".*/\1/p' "$OUTPUT" | head -1)"
  [ -n "$OLD_DATE" ] && KEEP_DATE="$OLD_DATE"
fi

# roff treats a leading '.' or '\'' as a request, and a bare '-' as a hyphen
# rather than the minus an option needs.
escape_roff() {
  sed -e 's/\\/\\e/g' -e 's/-/\\-/g' -e 's/^[.'"'"']/\\\&&/'
}

HELP="$("$BINARY" --help)"

# The lines of one section of --help, between its heading and the next blank
# line, with wrapped continuation lines joined back onto their entry.
# awk reads to the end rather than exiting at the section's end: exiting
# would leave printf writing into a closed pipe, and SIGPIPE under pipefail
# fails the build where pipes are small (OpenBSD's).
section() {
  printf '%s\n' "$HELP" | awk -v want="$1" '
    done           { next }
    $0 == want ":" { on = 1; next }
    on && /^$/     { on = 0; done = 1; next }
    on {
      if ($0 ~ /^                    /) {     # a continuation line
        sub(/^ +/, "")
        # A term too long for its column has its description start on the
        # next line; keep the two-space gap that separates the two.
        entry = entry (entry ~ /[^ ]  +[^ ]/ ? " " : "  ") $0
        next
      }
      if (entry != "") print entry
      entry = $0
    }
    END { if (entry != "") print entry }
  '
}

# "  term   description" -> .TP entries. Terms are bold, with an argument after
# "=" or a space in italics.
entries() {
  local kind="$1"
  while IFS= read -r line; do
    local term desc
    term="$(printf '%s' "$line" | sed -E 's/^ +//; s/ {2,}.*$//')"
    desc="$(printf '%s' "$line" | sed -E 's/^ +[^ ].*[^ ] {2,}//; s/^ +//' | escape_roff)"
    if [ "$kind" = "option" ]; then
      term="$(printf '%s' "$term" | escape_roff \
              | sed -E 's/(\\-\\-[a-z-]+)=([A-Z]+)/\\fB\1\\fR=\\fI\2\\fR/; s/(\\-\\-[a-z-]+)\[=([a-z]+)\]/\\fB\1\\fR[=\\fB\2\\fR]/; s/^(\\-[A-Za-z]),/\\fB\1\\fR,/; s/^(\\-\\-[a-z-]+)$/\\fB\1\\fR/')"
    else
      local name args
      name="${term%% *}"
      args=""
      [ "$name" != "$term" ] && args=" \\fI${term#* }\\fR"
      term="\\fB${name}\\fR${args}"
    fi
    printf '.TP\n%s\n%s\n' "$term" "$desc"
  done
}

TMP="$(mktemp)"
trap 'rm -f "$TMP" "$TMP.a" "$TMP.b"' EXIT

