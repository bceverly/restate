.SH SECURITY CONSIDERATIONS
A complete scan reads every file on the machine and so runs as root. It opens
everything with
.B O_NOFOLLOW
relative to its parent directory, and refuses a file or directory that is not
the one it examined a moment earlier, so an unprivileged user cannot redirect
it by swapping a directory for a symbolic link mid-scan.
.PP
An image or index is input when it is read back. The JSON and tar parsers
are strict, bounded and fuzzed, and they reject any path that is not clean
and absolute, so that an index cannot name a location outside the tree it
describes.
.PP
.B restate
runs eight programs, each for something it should not do itself:
.BR gzip (1),
.BR pigz (1)
(the same compression on every core, used in place of gzip to write an
image where it is installed),
.BR curl (1),
.BR gpgv (1),
.BR gpg (1),
.BR gpgconf (1)
(to stop the agent gpg starts when it signs),
.BR sh (1)
(the script
.B restore \-\-packages
writes, which runs apt, snap and the rest as a person would; every name and
version in it is checked against what its package manager allows, and every
other word quoted, so it runs nothing the image's tree wrote) and
.BR ssh-keygen (1)
(new SSH host keys, for
.BR "restore \-\-as" ).
Each is run from a fixed absolute path \-
.IR /usr/bin ,
then
.I /usr/local/bin
for all but gzip, then
.IR /bin ;
.I /bin/sh
first for sh \- never through
.BR PATH ,
and only if root owns both the program and its directory and nobody else
can write to them, because restate runs as root and a program another user
could replace would run as root too. They are started with
.BR posix_spawn (3),
with no shell, and with an environment of
.BR PATH ,
.B LC_ALL
and what that one program needs (see
.BR ENVIRONMENT ).
restate itself opens no network connection;
curl is held to HTTPS, redirects included, and ignores
.IR ~/.curlrc .
Nothing downloaded is used until its checksum has been verified against a
signature by the pinned vendor key. The one exception to HTTPS is
.BR \-\-fetch\-sources ,
and
.BR "baseline fetch" ,
which fetch apt's indexes and packages the way apt does, plain http
included, and believe them only once
.B gpgv
has checked the index's signature, and the index's digests what was
fetched.
.PP
A repository is made 0700, and everything in it 0600. One that is not
encrypted belongs somewhere only root reads; one made with
.B init \-\-encrypt\-to
can be kept anywhere, and so can what
.B export \-\-encrypt\-to
makes of a snapshot. The capturing machine's copy of what it wrote into an
encrypted repository, under
.IR /var/cache/restate/repositories/ ,
is plain text, root's alone, and describes only that machine's own files.
Encryption is not authentication: a snapshot's signature covers its index,
and its index every file's digest; each file is checked against its digest
as it is restored or exported.
.PP
With
.BR "capture \-\-quiesce" ,
it also runs hooks, held to the same rule \- root's, file and directory,
and writable by no one else \- with no shell of restate's own, an
environment of
.BR PATH " (the system's administration directories), " LC_ALL
and the
.B RESTATE_
variables, and a time limit.
